static void test_cpio_start(void)
{
	g_cpio_test_ok = test_cpio_run() ? true : false;
}

static bool test_cpio_done(void) { return true; }
static bool test_cpio_passed(void) { return g_cpio_test_ok; }

static const struct selftest cpio_test = {
	.name   = "cpio",
	.start  = test_cpio_start,
	.done   = test_cpio_done,
	.passed = test_cpio_passed,
};

void test_cpio_init(void)
{
	if (selftest_register(&cpio_test) < 0) {
		kprintf("[test_cpio] WARNING: register failed\n");
	} else {
		kprintf("[test_cpio] registered\n");
	}
}

/**
 * test_cpio_run() — 同步执行完整 CPIO 单元测试
 *
 * 直启路径调用此函数，可在线程/调度器启动前验证
 * CPIO 解析器的正确性。返回 true 表示全部 5 项测试通过。
 */
bool test_cpio_run(void)
{
	bool ok = true;

	/* 1. cpio_init */
	kprintf("[test_cpio] 1/5 cpio_init valid...");
	if (cpio_init(test_cpio_archive, sizeof(test_cpio_archive)) != 0) {
		kprintf(" FAIL: valid archive rejected\n");
		return false;
	}
	kprintf(" ok\n");

	kprintf("[test_cpio] 2/5 cpio_init invalid...");
	if (cpio_init(NULL, 0) != -1) {
		kprintf(" FAIL: NULL,0 should fail\n");
		return false;
	}
	if (cpio_init(test_cpio_archive, 10) != -1) {
		kprintf(" FAIL: too-short buffer should fail\n");
		return false;
	}
	/* Bad magic */
	{
		char bad_magic[110] = {"070702"}; /* wrong version */
		memset(bad_magic + 6, '0', 104);
		bad_magic[54 + 1] = '1'; /* filesize=1 */
		bad_magic[94 + 1] = '1'; /* namesize=1 */
		if (cpio_init(bad_magic, sizeof(bad_magic)) != -1) {
			kprintf(" FAIL: bad magic should fail\n");
			return false;
		}
	}
	kprintf(" ok\n");

	/* 2. cpio_next: iterate */
	if (cpio_init(test_cpio_archive, sizeof(test_cpio_archive)) != 0) {
		kprintf(" re-init failed\n");
		return false;
	}

	kprintf("[test_cpio] 3/5 cpio_next iteration...");
	{
		struct cpio_entry e;
		int count = 0;
		while (cpio_next(&e) == 1)
			count++;
		if (count != 2) {
			kprintf(" FAIL: expected 2 files, got %d\n", count);
			return false;
		}
	}
	kprintf(" ok\n");

	/* 3. cpio_find */
	kprintf("[test_cpio] 4/5 cpio_find hello.txt...");
	{
		struct cpio_entry e;
		if (cpio_find("hello.txt", &e) != 1) {
			kprintf(" FAIL: hello.txt not found\n");
			return false;
		}
		if (e.size != 27) {
			kprintf(" FAIL: hello.txt size %u != 27\n", e.size);
			return false;
		}
		if (memcmp(e.data, "Hello from CPIO unit test!\n", 27) != 0) {
			kprintf(" FAIL: hello.txt content mismatch\n");
			return false;
		}
	}
	kprintf(" ok\n");

	{
		struct cpio_entry e;
		if (cpio_find("numbers.bin", &e) != 1) {
			kprintf(" FAIL: numbers.bin not found\n");
			return false;
		}
		if (e.size != 5) {
			kprintf(" FAIL: numbers.bin size %u != 5\n", e.size);
			return false;
		}
		const uint8_t *d = (const uint8_t *)e.data;
		if (d[0] != 0x00 || d[1] != 0x01 || d[2] != 0x02 ||
				d[3] != 0x03 || d[4] != 0xFF) {
			kprintf(" FAIL: numbers.bin content mismatch\n");
			return false;
		}
	}
	kprintf("    numbers.bin ok\n");

	/* 4. cpio_find: edge cases */
	kprintf("[test_cpio] 5/5 cpio_find edge cases...");
	{
		struct cpio_entry e;
		if (cpio_find("nonexistent.txt", &e) != 0) {
			kprintf(" FAIL: nonexistent file should return 0\n");
			return false;
		}
		if (cpio_find(NULL, &e) != -1) {
			kprintf(" FAIL: NULL name should return -1\n");
			return false;
		}
		if (cpio_find("hello.txt", NULL) != -1) {
			kprintf(" FAIL: NULL entry should return -1\n");
			return false;
		}
	}
	kprintf(" ok\n");

	/* Re-init for cleanup / follow-up */
	cpio_init(test_cpio_archive, sizeof(test_cpio_archive));

	kprintf("[test_cpio] %s\n", ok ? "PASSED" : "FAILED");

	return ok;
}
